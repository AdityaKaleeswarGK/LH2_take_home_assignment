def test_a_failed_provision_is_not_stamped(tmp_path: Path, monkeypatch) -> None:
    """A broken environment must be retried, not remembered."""
    from stress_stack import hygiene
    from stress_stack.hygiene import provision_test_environment

    root = tmp_path / "repo"
    root.mkdir()
    (root / "pyproject.toml").write_text('[project]\nname = "app"\n', encoding="utf-8")
    environment_root = tmp_path / "tools"
    calls: list[list[str]] = []
    _venv(monkeypatch, environment_root, calls)

    class _Broken:
        ok = False

        def failure_detail(self) -> str:
            return "no network"

    monkeypatch.setattr(hygiene, "install", lambda p, pkgs, **k: (calls.append(pkgs), _Broken())[1])

    record = provision_test_environment(root, environment_root)
    assert record["installed"] is False
    assert not (environment_root / "provision_stamp.json").exists()
